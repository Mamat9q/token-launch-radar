// Token Radar's model (radar-2): one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol that passes the watchlist's own no-token rule,
// applied to the whole snapshot rather than only to the watchlist floor. A
// protocol is rankable when DefiLlama's record carries no token for it
// (mcap_usd, gecko_id and symbol all null) and it is not a wrapped, staked or
// bridged product of a token that already trades: its category is not Bridge,
// Canonical Bridge, Cross Chain Bridge, Liquid Staking, Liquid Restaking,
// Restaked BTC or CEX, its name ends in no version marker, carries no whole
// word wrapped, staked or staking, and begins with no exchange's name. (The
// house's rule names Bridge and Canonical Bridge; Cross Chain Bridge names
// the same kind of product under DefiLlama's other label, so it is excluded
// here too: one row, Circle Gateway, a product of Circle, whose USDC trades.)
//
// The snapshot carries no parentProtocol field, so a sub-product of a tokened
// parent that passes the name and category tests stays on the board as a
// record with no token. The dashboard says a protocol "records no token",
// never that it has none.
//
// Implied value follows only from the snapshot's own figures:
//
//   base       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.02 x min(chains, 5)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row.
// Live-token protocols are kept apart and shown with the market's own values,
// never mixed into the ranked board.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

